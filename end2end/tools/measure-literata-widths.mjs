// Measures the advance width of Literata's characters in Chromium and writes
// src/literata_widths.rs, the table the build uses to estimate how wide a
// Markdown table is (src/table_widths.rs).
//
// Run from end2end/ (it imports Playwright from node_modules, so it adds no
// dependency of its own):
//
//   node tools/measure-literata-widths.mjs
//
// Only the generated Rust file is meant to be committed with it; run the
// script again if the font files in assets/fonts/literata/ change.
//
// How: each font file is loaded as a FontFace, then a canvas measures every
// character alone at 1000px, so the advance in pixels is the advance in
// thousandths of em. A character is measured alone on purpose: kerning
// between pairs is ignored (it only ever makes text a hair narrower, and a
// build-time estimate has to err on the wide side). A character the font
// lacks would be measured in a fallback font; the script detects that by
// measuring it again behind two different fallbacks and fails if the widths
// differ.
import { chromium } from '@playwright/test';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const out = resolve(root, 'src/literata_widths.rs');

// U+0020-U+007E, U+00A0-U+00FF, the dashes, quotes and ellipsis the articles use.
const codePoints = [
  ...range(0x20, 0x7e),
  ...range(0xa0, 0xff),
  0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2026,
];
function range(from, to) {
  return Array.from({ length: to - from + 1 }, (_, i) => from + i);
}

const fonts = [
  { weight: 400, name: 'REGULAR', file: 'literata-latin-400-normal.woff2' },
  { weight: 700, name: 'BOLD', file: 'literata-latin-700-normal.woff2' },
];

const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent('<!doctype html><meta charset="utf-8"><canvas id="c"></canvas>');

const measured = {};
for (const { weight, name, file } of fonts) {
  const base64 = readFileSync(resolve(root, 'assets/fonts/literata', file)).toString('base64');
  measured[name] = await page.evaluate(
    async ({ base64, weight, codePoints }) => {
      const family = `LiterataMeasure${weight}`;
      const face = new FontFace(family, `url(data:font/woff2;base64,${base64}) format("woff2")`, {
        weight: String(weight),
      });
      document.fonts.add(await face.load());
      await document.fonts.ready;
      const context = document.getElementById('c').getContext('2d');
      const width = (stack, text) => {
        context.font = `${weight} 1000px ${stack}`;
        return context.measureText(text).width;
      };
      return codePoints.map((cp) => {
        const text = String.fromCodePoint(cp);
        const own = width(`"${family}", monospace`, text);
        const other = width(`"${family}", serif`, text);
        return { cp, own, other };
      });
    },
    { base64, weight, codePoints },
  );
}
await browser.close();

function thousandths(entry) {
  // Fallback check: the width must not depend on the fallback font.
  if (Math.abs(entry.own - entry.other) > 0.01) {
    throw new Error(`U+${entry.cp.toString(16)} is not in the font (width depends on the fallback)`);
  }
  // Round up: the estimate may be a hair wide, never narrow.
  return Math.ceil(entry.own - 0.001);
}

let source = `// Generated by end2end/tools/measure-literata-widths.mjs: do not edit by hand.
// Regenerate, from the end2end/ folder, with:
//
//   node tools/measure-literata-widths.mjs
//
// Advance widths of Literata (assets/fonts/literata/, weights 400 and 700, upright), in
// thousandths of em, measured in Chromium with a canvas at 1000px, one character at a time
// (so kerning is ignored: it mostly makes pairs narrower), each rounded up to a whole
// thousandth. Each table is sorted by character, for binary search.
`;
for (const { name } of fonts) {
  const rows = measured[name].map((entry) => `    (${rustChar(entry.cp)}, ${thousandths(entry)}),`);
  source += `\npub const LITERATA_${name}: [(char, u16); ${rows.length}] = [\n${rows.join('\n')}\n];\n`;
}
writeFileSync(out, source);
console.log(`wrote ${out}`);

function rustChar(cp) {
  if (cp === 0x27) return "'\\''";
  if (cp === 0x5c) return "'\\\\'";
  if (cp > 0x20 && cp < 0x7f) return `'${String.fromCodePoint(cp)}'`;
  return `'\\u{${cp.toString(16)}}'`;
}
