//! The site's breakpoints: the screen widths at which the layout changes. They are written in
//! one place, `config/breakpoints.txt`, read by the build, by the Rust checks of the classes and
//! by the browser tests, and written out for the stylesheet to `target/generated/breakpoints.css`,
//! which `style/input.css` imports.
//!
//! The stylesheet cannot read a configuration file by itself, and a width written there would
//! be a second place to change, one the tests and the checks would not know about. So the
//! stylesheet sets no breakpoint, and moving one is a change of one number in the file. What
//! changes at each breakpoint is not here: it stays in the components, as classes with the
//! breakpoint's name as prefix (`md:...`).
//!
//! The file has one line `name=width` for each breakpoint: the name is made of small ASCII
//! letters and digits, as the prefixes Tailwind accepts, and the width is a positive whole number
//! of pixels (a breakpoint says which devices the site addresses, and devices are measured in
//! pixels). Blank lines and lines that start with `#` are ignored.
//!
//! The parsing is pure (text in, value or error out) so every refusal has a test that needs no
//! disk; the build program reads the file and passes its text in.

use std::fmt::Write;

/// Where the breakpoints are written, relative to the repository's root.
pub const FILE: &str = "config/breakpoints.txt";

/// One breakpoint: its name, the prefix of the classes that change there, and its width in pixels.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Breakpoint {
    pub name: String,
    pub width: u32,
}

/// What is wrong in the file.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum Problem {
    #[error("`{0}` is not in the form name=width")]
    NotNameWidth(String),
    #[error("`{0}` is not a name: it must be made only of small letters and digits")]
    BadName(String),
    #[error("`{0}` is not a width: it must be a positive whole number of pixels")]
    BadWidth(String),
    #[error("the name `{0}` is given more than once")]
    RepeatedName(String),
    #[error("the width {width} is given more than once (`{other}` has it too)")]
    RepeatedWidth { width: u32, other: String },
}

/// A problem, with the file and the line where it was found.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("{FILE}:{line}: {problem}")]
pub struct BreakpointsError {
    pub line: usize,
    pub problem: Problem,
}

/// The breakpoints of the file, in the order written.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Breakpoints(pub Vec<Breakpoint>);

// The range is written out because the word of the standard method's name, found in a source,
// makes Tailwind emit a stray utility of that name.
#[allow(clippy::manual_is_ascii_check)]
fn is_name(name: &str) -> bool {
    !name.is_empty()
        && name
            .chars()
            .all(|c| matches!(c, 'a'..='z') || c.is_ascii_digit())
}

/// Reads the text of `config/breakpoints.txt`.
pub fn parse(text: &str) -> Result<Breakpoints, BreakpointsError> {
    let mut found: Vec<Breakpoint> = Vec::new();
    for (index, line) in text.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let number = index + 1;
        let fail = |problem| BreakpointsError {
            line: number,
            problem,
        };
        let (name, width) = line
            .split_once('=')
            .map(|(name, width)| (name.trim(), width.trim()))
            .ok_or_else(|| fail(Problem::NotNameWidth(line.to_owned())))?;
        if !is_name(name) {
            return Err(fail(Problem::BadName(name.to_owned())));
        }
        let width_number = if width.chars().all(|c| c.is_ascii_digit()) {
            width.parse::<u32>().ok().filter(|width| *width > 0)
        } else {
            None
        }
        .ok_or_else(|| fail(Problem::BadWidth(width.to_owned())))?;
        if found.iter().any(|known| known.name == name) {
            return Err(fail(Problem::RepeatedName(name.to_owned())));
        }
        if let Some(known) = found.iter().find(|known| known.width == width_number) {
            return Err(fail(Problem::RepeatedWidth {
                width: width_number,
                other: known.name.clone(),
            }));
        }
        found.push(Breakpoint {
            name: name.to_owned(),
            width: width_number,
        });
    }
    Ok(Breakpoints(found))
}

/// The stylesheet text the build writes: a `@theme` block that clears Tailwind's own breakpoints
/// and sets the site's. `--breakpoint-*: initial` comes first in the same block, since it only
/// clears what was defined before it.
pub fn css(breakpoints: &Breakpoints) -> String {
    let mut out = format!(
        "/* Generated by the build from {FILE}. Do not edit. */\n\n\
         @theme {{\n  --breakpoint-*: initial;\n"
    );
    for Breakpoint { name, width } in &breakpoints.0 {
        writeln!(out, "  --breakpoint-{name}: {width}px;").unwrap();
    }
    out.push_str("}\n");
    out
}

/// The breakpoints in the repository, read from the disk as the build reads it: the ones the
/// Rust checks of the classes use.
#[cfg(test)]
pub fn real() -> Breakpoints {
    parse(include_str!("../../config/breakpoints.txt")).unwrap()
}

/// The class without its breakpoint prefix, when the prefix is one the file names. A class with
/// another prefix (`lg:` with only `md` and `xl`) is returned whole, so the check of ADR-001
/// does not find it among the utilities: Tailwind would ignore it without a word.
#[cfg(test)]
pub fn without_prefix<'a>(token: &'a str, breakpoints: &Breakpoints) -> &'a str {
    breakpoints
        .0
        .iter()
        .find_map(|breakpoint| {
            token
                .strip_prefix(breakpoint.name.as_str())
                .and_then(|rest| rest.strip_prefix(':'))
        })
        .unwrap_or(token)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn refused(text: &str) -> BreakpointsError {
        parse(text).unwrap_err()
    }

    #[test]
    fn reads_names_and_widths_ignoring_blank_lines_and_comments() {
        let found = parse("# a comment\n\nmd=768\n  xl = 1280  \n").unwrap();
        assert_eq!(
            found.0,
            vec![
                Breakpoint {
                    name: "md".into(),
                    width: 768
                },
                Breakpoint {
                    name: "xl".into(),
                    width: 1280
                },
            ]
        );
    }

    #[test]
    fn the_file_in_the_repository_is_valid() {
        assert!(!real().0.is_empty());
    }

    #[test]
    fn refuses_a_repeated_name() {
        let error = refused("md=768\nmd=1280\n");
        assert_eq!(error.line, 2);
        assert_eq!(error.problem, Problem::RepeatedName("md".into()));
        assert!(error.to_string().starts_with("config/breakpoints.txt:2:"));
    }

    #[test]
    fn refuses_a_repeated_width() {
        let error = refused("md=768\n\nxl=768\n");
        assert_eq!(error.line, 3);
        assert_eq!(
            error.problem,
            Problem::RepeatedWidth {
                width: 768,
                other: "md".into()
            }
        );
    }

    #[test]
    fn refuses_a_malformed_line() {
        let error = refused("# header\nmd 768\n");
        assert_eq!(error.line, 2);
        assert_eq!(error.problem, Problem::NotNameWidth("md 768".into()));
    }

    #[test]
    fn refuses_a_name_not_made_of_small_letters_and_digits() {
        for name in ["", "MD", "m-d", "m d", "mé"] {
            let error = refused(&format!("{name}=768"));
            assert_eq!(error.problem, Problem::BadName(name.into()), "{name:?}");
            assert_eq!(error.line, 1);
        }
    }

    #[test]
    fn refuses_a_width_that_is_not_a_positive_whole_number() {
        for width in [
            "",
            "0",
            "-768",
            "+768",
            "76.8",
            "48rem",
            "abc",
            "99999999999999999999",
        ] {
            let error = refused(&format!("md=768\nxl={width}"));
            assert_eq!(error.problem, Problem::BadWidth(width.into()), "{width:?}");
            assert_eq!(error.line, 2);
        }
    }

    #[test]
    fn the_stylesheet_clears_tailwinds_breakpoints_and_sets_the_sites() {
        let css = css(&parse("md=768\nxl=1280\n").unwrap());
        assert!(css.contains("@theme {\n  --breakpoint-*: initial;\n"));
        // The variables' names are built, not written whole: Tailwind takes a variable
        // named in a source it scans as used, and would emit it in the page's `:root`.
        for (name, width) in [("md", 768), ("xl", 1280)] {
            assert!(css.contains(&format!("{}-{name}: {width}px;", "--breakpoint")));
        }
    }

    #[test]
    fn a_changed_width_moves_in_the_stylesheet() {
        let css = css(&parse("md=800\nxl=1280\n").unwrap());
        assert!(css.contains(&format!("{}-md: 800px;", "--breakpoint")));
        assert!(!css.contains("768"));
    }

    #[test]
    fn only_the_prefixes_of_the_file_are_taken_off_a_class() {
        let breakpoints = parse("md=768\nxl=1280\n").unwrap();
        assert_eq!(without_prefix("md:title", &breakpoints), "title");
        assert_eq!(without_prefix("xl:title", &breakpoints), "title");
        assert_eq!(without_prefix("title", &breakpoints), "title");
        assert_eq!(without_prefix("lg:title", &breakpoints), "lg:title");
    }
}
