    /// The text of the code element as the browser copies it: line wrappers removed, entities
    /// decoded.
    fn code_text(html: &str) -> String {
        let start = html.find("<code").unwrap();
        let start = start + html[start..].find('>').unwrap() + 1;
        let body = &html[start..html.find("</code>").unwrap()];
        let mut text = String::new();
        let mut rest = body;
        while let Some(open) = rest.find('<') {
            text.push_str(&rest[..open]);
            rest = &rest[rest.find('>').unwrap() + 1..];
        }
        text.push_str(rest);
        text.replace("&lt;", "<")
            .replace("&gt;", ">")
            .replace("&quot;", "\"")
            .replace("&amp;", "&")
    }

