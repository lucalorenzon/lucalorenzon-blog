//! The site's icons: drawn by the build from the `icondata` crate, written into a CSS file
//! for Tailwind, never copied by hand into the stylesheet.
//!
//! An icon becomes a Tailwind utility (`icon-<name>`) that uses the drawing as a mask. The
//! element that carries it takes the icon's shape from the mask and its colour from its own
//! `background-color`, so the icon follows the site's colours and the light and dark schemes.
//! Only Bootstrap Icons' set is compiled in (`Cargo.toml`); its licence and attribution are in
//! `assets/icons/`.

use icondata::{BsTextWrap, Icon};
use std::fmt::Write;

/// An icon the site uses: the name of its utility, and its drawing.
struct SiteIcon {
    name: &'static str,
    drawing: Icon,
}

/// Every icon of the site. The wrap toggle's, for now.
const ICONS: [SiteIcon; 1] = [SiteIcon {
    name: "text-wrap",
    drawing: BsTextWrap,
}];

/// The drawing as a stand-alone SVG document.
fn svg(drawing: Icon) -> String {
    format!(
        "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"{}\" fill=\"{}\">{}</svg>",
        drawing.view_box.unwrap_or("0 0 24 24"),
        drawing.fill.unwrap_or("currentColor"),
        drawing.data
    )
}

/// The SVG as a CSS `data:` URL, between double quotes. `%`, `#`, `<`, `>`, `"`, `\` and the
/// line breaks are percent-encoded; the rest is safe in a quoted CSS URL.
fn data_url(svg: &str) -> String {
    let mut out = String::from("data:image/svg+xml,");
    for character in svg.chars() {
        match character {
            '%' => out.push_str("%25"),
            '#' => out.push_str("%23"),
            '<' => out.push_str("%3C"),
            '>' => out.push_str("%3E"),
            '"' => out.push_str("%22"),
            '\\' => out.push_str("%5C"),
            '\n' => out.push_str("%0A"),
            '\r' => out.push_str("%0D"),
            other => out.push(other),
        }
    }
    out
}

/// The CSS for `style/input.css`: one `@utility icon-<name>` for each icon. The prefixed
/// `-webkit-mask-image` is written too, for the browsers that still need it.
pub fn css() -> String {
    let mut out = String::from("/* Generated by the build from src/icons.rs. Do not edit. */\n");
    for icon in &ICONS {
        let url = data_url(&svg(icon.drawing));
        let _ = write!(
            out,
            "\n@utility icon-{} {{\n  \
             -webkit-mask-image: url(\"{url}\");\n  \
             mask-image: url(\"{url}\");\n  \
             -webkit-mask-repeat: no-repeat;\n  \
             mask-repeat: no-repeat;\n  \
             -webkit-mask-position: center;\n  \
             mask-position: center;\n  \
             -webkit-mask-size: contain;\n  \
             mask-size: contain;\n}}\n",
            icon.name
        );
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_css_holds_the_drawing_of_the_wrap_icon_from_icondata() {
        let text = css();
        assert!(text.starts_with("/* Generated by the build"));
        assert!(text.contains("@utility icon-text-wrap {\n"));
        assert!(text.contains("mask-image: url(\"data:image/svg+xml,"));
        assert!(text.contains("mask-repeat: no-repeat;"));
        assert!(text.contains("mask-position: center;"));
        assert!(text.contains("mask-size: contain;"));
        let encoded_path = data_url(BsTextWrap.data);
        let encoded_path = encoded_path.strip_prefix("data:image/svg+xml,").unwrap();
        assert!(text.contains(encoded_path));
        assert!(text.contains("viewBox=%220 0 16 16%22"));
    }

    #[test]
    fn the_data_url_has_no_character_that_breaks_a_css_url() {
        let url = data_url(&svg(BsTextWrap));
        let payload = url.strip_prefix("data:image/svg+xml,").unwrap();
        for forbidden in ['<', '>', '#', '"', '\n', '\\'] {
            assert!(!payload.contains(forbidden), "{forbidden:?}");
        }
        assert!(payload.starts_with("%3Csvg"));
    }

    #[test]
    fn a_percent_sign_is_encoded_first_and_once() {
        assert_eq!(
            data_url("50%<#>\"\n"),
            "data:image/svg+xml,50%25%3C%23%3E%22%0A"
        );
    }

    #[test]
    fn the_drawing_is_wrapped_in_its_own_view_box() {
        let text = svg(BsTextWrap);
        assert!(text.contains("viewBox=\"0 0 16 16\""));
        assert!(text.contains(BsTextWrap.data));
    }

    #[test]
    fn the_stylesheet_holds_no_drawing_written_by_hand() {
        let stylesheet = include_str!("../style/input.css");
        assert!(!stylesheet.contains("data:image/svg"));
        assert!(!stylesheet.contains("<svg"));
    }
}
